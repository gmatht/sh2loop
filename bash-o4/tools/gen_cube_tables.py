#!/usr/bin/env python3
"""Generate the bash cube tables from sh2perl/runtime/fbdev.c.

WHY A GENERATOR AND NOT A HAND-TRANSCRIPTION: fbdev.c already has one
transcription bug on record (CUBE_P), and a hand-copied 72-number
geometry table is a SECOND source of truth about the same cube. The
generator reads the arrays straight out of the C and emits bash
assignments, so the two cannot drift; `--check` re-reads the C and
diffs the result against the committed bash, which is what a test
should assert.

Usage:
  tools/gen_cube_tables.py [--c PATH] [--check]
"""
import argparse
import re
import sys

# The arrays the rasterizer needs, in the order they are emitted.
ARRAYS = ["CUBE_P", "CUBE_SHADE", "CUBE_I", "CUBE_UV", "FACE_N"]

HEADER = """\
# GENERATED by bash-o4/tools/gen_cube_tables.py from
# sh2perl/runtime/fbdev.c — DO NOT EDIT BY HAND.
#
# The device's own cube tables, transcribed verbatim. A hand-copied
# geometry table is a second source of truth about the same cube, and
# fbdev.c already has one transcription bug on record (CUBE_P); the
# generator is what makes "the bash and the C agree" checkable rather
# than reviewed.
"""


def extract(src: str, name: str) -> list[str]:
    """The integer literals of one array, in order."""
    m = re.search(
        r"static const [A-Za-z0-9_]+ " + name + r"\[[^\]]*\]\s*=\s*\{(.*?)\};",
        src,
        re.S,
    )
    if not m:
        # FACE_N is 2-D: `static const int8_t FACE_N[6][3] = {...}`
        m = re.search(
            r"static const [A-Za-z0-9_]+ " + name + r"\[[^\]]*\]\[[^\]]*\]\s*=\s*\{(.*?)\};",
            src,
            re.S,
        )
    if not m:
        raise SystemExit(f"gen_cube_tables: {name} not found in the C source")
    body = m.group(1)
    # Strip /* ... */ comments, which FACE_N carries inline.
    body = re.sub(r"/\*.*?\*/", " ", body, flags=re.S)
    return re.findall(r"-?\d+", body)


def emit(src: str) -> str:
    out = [HEADER]
    for name in ARRAYS:
        nums = extract(src, name)
        # A flat bash array, one number per line: readable in a diff and
        # trivially indexed 0-based, which is what the C does.
        out.append(f"{name}=(")
        for i in range(0, len(nums), 12):
            out.append("  " + " ".join(nums[i : i + 12]))
        out.append(")")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--c", default=None, help="path to fbdev.c")
    ap.add_argument("--check", action="store_true", help="diff against the committed file")
    a = ap.parse_args()

    here = __import__("os").path.dirname(__import__("os").path.abspath(__file__))
    c_path = a.c or __import__("os").path.join(here, "..", "..", "sh2perl", "runtime", "fbdev.c")
    with open(c_path) as f:
        src = f.read()
    generated = emit(src)

    out_path = __import__("os").path.join(here, "..", "src", "sh", "cube_tables.sh")
    if a.check:
        try:
            on_disk = open(out_path).read()
        except OSError as e:
            print(f"gen_cube_tables: cannot read {out_path}: {e}", file=sys.stderr)
            return 1
        if on_disk != generated:
            print(
                "gen_cube_tables: the committed cube tables differ from "
                f"fbdev.c ({c_path}); re-run without --check",
                file=sys.stderr,
            )
            return 1
        print("gen_cube_tables: cube tables match fbdev.c")
        return 0

    with open(out_path, "w") as f:
        f.write(generated)
    print(f"wrote {out_path} ({len(generated)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
