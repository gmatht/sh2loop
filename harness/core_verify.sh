#!/usr/bin/env bash
# core_verify.sh — build an ISOLATED otranspilerl-cli linked against the CORE
# worktree, and print its path. PLAN §11 marketplace; the core worker's gate.
#
# WHY THIS EXISTS
#   run_core_worker.sh used to point at
#     sh2perl/backends/core/otranspilerl/target/debug/otranspilerl-cli
#   which DOES NOT EXIST (the core worktree's manifest defines no such bin,
#   and its `otranspilerl/` dir is worktree-ignored). The missing command
#   produced empty stdout for every example, and check_qx_shir.py's
#   "invalid A1 JSON" line was counted by `grep -c FAIL` — producing a
#   meaningless "A1-native=555" that looked like 555 real lowering defects.
#
#   fail-estree does not fix it either: SH2PERL_DIR only swaps the EXAMPLE
#   tree; the gate still builds and runs the MAIN checkout's compiler, so the
#   "core" probe was a hybrid of the core corpus + the main compiler.
#
# WHAT THIS DOES
#   The workspace `otranspilerl` crate is a thin 2-file wrapper whose only
#   dependency is `debashl = { path = "../sh2perl" }`. So linking the CORE
#   worktree is exactly a matter of building that same wrapper against a
#   different debashl path. We create a temporary crate under .core-verify/
#   that points at sh2perl/backends/core, build it into an isolated target
#   dir (.core-verify-target/), print the binary path, and delete the
#   temporary crate on exit. The MAIN compiler target and binary are never
#   touched — the same isolation pattern main_loop_shir.pl uses.
#
# Usage:
#   bin=$(harness/core_verify.sh)          # build (or reuse) and print the path
#   harness/core_verify.sh --rebuild      # force a rebuild first
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SUB="$ROOT/sh2perl"                       # the sh2perl repo (worktree parent)
CORE="$SUB/backends/core"                 # the CORE worktree
# TEMPORARY wrapper crate, PER-PROCESS. It used to be a single fixed path
# ($ROOT/.core-verify), which made two concurrent runs destroy each other:
# each writes the crate, then `trap cleanup EXIT` does `rm -rf "$CRATE"`, so
# whichever finished first deleted the directory the other was still building
# in. The loser failed instantly with an empty stdout, which the core worker
# reported as "isolated core build FAILED" with NO cargo output — reproduced
# deterministically by running two at once (A rc=0, B rc=1, every round).
# A per-pid crate makes the trap safe by construction: it can only ever remove
# its own directory. The target dir stays SHARED (that is the point — it dedupes
# the dep build), and cargo's own target lock serialises the compiles.
CRATE="$ROOT/.core-verify.$$"             # temporary wrapper crate (gitignored)
TARGET="$ROOT/.core-verify-target"        # isolated cargo target (gitignored)
BIN="$TARGET/debug/otranspilerl-cli"

[ -d "$CORE/src" ] || { echo "core_verify: no core worktree at $CORE" >&2; exit 2; }

rebuild=0
for a in "$@"; do
  case "$a" in
    --rebuild) rebuild=1 ;;
    *) echo "core_verify: unknown option $a" >&2; exit 2 ;;
  esac
done

# A cached binary is only trusted if it is NEWER than every source it links:
# the wrapper's own sources and the whole core worktree. Compare the newest
# mtime against the binary's.
if [ "$rebuild" -eq 0 ] && [ -x "$BIN" ]; then
  newest=$(find "$ROOT/otranspilerl/src" "$ROOT/otranspilerl/Cargo.toml" "$CORE/src" "$CORE/Cargo.toml" -type f -newer "$BIN" -print -quit 2>/dev/null || true)
  if [ -z "$newest" ]; then
    echo "$BIN"
    exit 0
  fi
fi

cleanup() { rm -rf "$CRATE"; }
trap cleanup EXIT

mkdir -p "$CRATE/src"
cat > "$CRATE/Cargo.toml" <<EOF
# TEMPORARY crate — generated by harness/core_verify.sh, deleted on exit.
# The workspace otranspilerl crate minus the debashl path pin: it links the
# CORE worktree instead of the main checkout, so the core gate measures the
# core's own compiler.
[package]
name = "otranspilerl-core-verify"
version = "0.0.0"
edition = "2021"
publish = false

[lib]
name = "otranspilerl"
path = "src/lib.rs"
crate-type = ["rlib"]

[[bin]]
name = "otranspilerl-cli"
path = "src/main.rs"

[dependencies]
debashl = { path = "$CORE" }
serde_json = "1"

[workspace]
EOF

# Reuse the workspace wrapper's real sources verbatim (a copy, so the temp
# crate can never write into the workspace). Only the debashl pin differs.
cp "$ROOT/otranspilerl/src/lib.rs"  "$CRATE/src/lib.rs"
cp "$ROOT/otranspilerl/src/main.rs" "$CRATE/src/main.rs"
if [ -f "$ROOT/otranspilerl/src/wasi.rs" ]; then
  cp "$ROOT/otranspilerl/src/wasi.rs" "$CRATE/src/wasi.rs"
fi

# ── tolerate transforms the linked core has not adopted ───────────────
# `src/lib.rs` is copied VERBATIM so the gate builds the workspace wrapper
# against THIS worktree's debashl. But that file evolves with the main
# checkout: a worker that adds a transform to `ingest` (the
# `capture-node-fold` precedent) edits it too, while a backend worktree
# receives shared-core changes only by MERGE (`setup_backends.sh --sync`),
# not on demand. The verbatim copy then fails to resolve
# `debashl::transforms::<name>` (E0433) and EVERY iteration is skipped as
# "isolated core build FAILED" — for a reason that has nothing to do with the
# core under test (observed 2026-10-22 from 10:05 on: eight consecutive skips
# before this guard).
#
# `...::name::` is a NAMESPACE path (a module); `...::name(` is an fn, which
# ships with the core either way, so only the namespace form is considered.
# For each module the target core does not declare, comment out exactly those
# statement lines — the gate then tests the core that EXISTS, skipping only a
# normalisation it has itself not adopted. Every namespace reference is a
# single-line statement ending in `;` (verified over the whole file), so a
# whole-line comment cannot unbalance the syntax.
drop_unadopted_transforms() {
  _lib="$1"; _core="$2"
  for _ns in transforms shir_passes; do
    case "$_ns" in
      transforms)  _decl="$_core/src/transforms.rs" ;;
      shir_passes) _decl="$_core/src/shir_passes/mod.rs" ;;
      *) continue ;;
    esac
    [ -f "$_decl" ] || continue
    for _m in $(command grep -oE "debashl::${_ns}::[a-z_0-9]+::" "$_lib" 2>/dev/null \
                | sed -E "s#debashl::${_ns}::([a-z_0-9]+)::#\\1#" | sort -u); do
      if command grep -qE "^[[:space:]]*pub mod ${_m};" "$_decl"; then
        continue
      fi
      sed -i -E "s#^([[:space:]]*)(.*debashl::${_ns}::${_m}::.*)\$#\\1// core-gate(unadopted ${_ns}::${_m}): \\2#" "$_lib"
      echo "core_verify: linked core lacks ${_ns}::${_m} — commenting its ingest call(s) out of the gate copy" >&2
    done
  done

  # ── tolerate TOP-LEVEL modules the linked core has not adopted ────────
  # The wrapper's dispatch arm `debashl::<mod>::<fn>(…)` references a
  # top-level backend module (fish_backend, zsh_backend, …). Those "copied
  # from backends/<lang>" modules were added to sh2perl/src/lib.rs by the
  # fleet, to the WORKSPACE wrapper's benefit — but the CORE worktree's
  # debashl only grows them through the normal merge discipline, not on
  # demand. When the wrapper gains an arm before the core has the module,
  # every iteration fails E0433 and the gate skips as "isolated core build
  # FAILED" for a reason unrelated to the core under test (observed
  # 2026-10-22 from 12:15: fish_backend/zsh_backend, then every later
  # iteration skipped).
  #
  # Detection: the WRAPPER's dispatch arms reference `debashl::<name>_backend::`
  # (found in `$1`, the copied otranspilerl/src/lib.rs). A module is ADOPTED
  # iff the core worktree's own lib declares `mod <name>_backend;` OR
  # `src/<name>_backend.rs` exists under it (checked against `$2`, the CORE
  # worktree). If NEITHER, the arm cannot resolve (E0433): comment it out.
  # Filtering against the CORE worktree's decls (not the wrapper's) matters —
  # sh2perl/src/lib.rs (the debashl namespace) already declares fish/zsh, so
  # testing the wrong file would never flag them.
  _lib="$1"; _core="$2"
  for _m in $(command grep -oE 'debashl::([a-z_0-9]+_backend)::' "$_lib" 2>/dev/null \
              | sed -E 's#debashl::([a-z_0-9]+_backend)::#\1#' | sort -u); do
    # adopted? decl in core's own lib, or module file present in core src/
    if command grep -qE "^[[:space:]]*(pub[[:space:]]+)?mod[[:space:]]+${_m};" "$_core/src/lib.rs" 2>/dev/null \
       || [ -f "$_core/src/${_m}.rs" ]; then
      continue
    fi
    # idempotent across a relaunch that re-copies lib.rs:
    command grep -q "core-gate(unadopted module ${_m})" "$_lib" && continue
    sed -i -E "s#^([[:space:]]*)(.*debashl::${_m}::.*)\$#\\1// core-gate(unadopted module ${_m}): \\2#" "$_lib"
    echo "core_verify: linked core lacks module ${_m} — commenting its dispatch arm(s) out of the gate copy" >&2
  done
}
drop_unadopted_transforms "$CRATE/src/lib.rs" "$CORE"

# A DANGLING $TARGET symlink makes `mkdir -p` fail with "File exists"
# (GNU mkdir cannot create the final component when it is a symlink whose
# target is absent) — which is exactly how the Core worker skipped every
# iteration from 2026-10-22 10:05 onward: the cargo scratch dir
# /mnt/wsl/tmpbtrfs went away with a WSL restart, leaving .core-verify-target
# pointing at nothing, and the plain mkdir error was reported as an
# "isolated core build FAILED". Drop a dead link before creating the
# directory so stale machine state can never block the gate again.
if [ -L "$TARGET" ] && [ ! -e "$TARGET" ]; then
  rm -f "$TARGET"
fi
mkdir -p "$TARGET"
"$ROOT/harness/build-lock.sh" --role core --share-target "$TARGET" -- \
  cargo build --manifest-path "$CRATE/Cargo.toml" --bin otranspilerl-cli >>"$ROOT/loop-core-worker.log" 2>&1 || {
  echo "core_verify: isolated core build FAILED (see loop-core-worker.log)" >&2
  exit 1
}

[ -x "$BIN" ] || { echo "core_verify: build produced no binary at $BIN" >&2; exit 1; }
echo "$BIN"
