#!/usr/bin/env bash
# core_verify.sh — build an ISOLATED otranspilerl-cli linked against the CORE
# worktree, and print its path. PLAN §11 marketplace; the core worker's gate.
#
# WHY THIS EXISTS
#   run_core_worker.sh used to point at
#     sh2perl/backends/core/otranspilerl/target/debug/otranspilerl-cli
#   which DOES NOT EXIST (the core worktree's manifest defines no such bin,
#   and its `otranspilerl/` dir is worktree-ignored). The missing command
#   produced empty stdout for every example, and check_qx_shir.py's
#   "invalid A1 JSON" line was counted by `grep -c FAIL` — producing a
#   meaningless "A1-native=555" that looked like 555 real lowering defects.
#
#   fail-estree does not fix it either: SH2PERL_DIR only swaps the EXAMPLE
#   tree; the gate still builds and runs the MAIN checkout's compiler, so the
#   "core" probe was a hybrid of the core corpus + the main compiler.
#
# WHAT THIS DOES
#   The workspace `otranspilerl` crate is a thin 2-file wrapper whose only
#   dependency is `debashl = { path = "../sh2perl" }`. So linking the CORE
#   worktree is exactly a matter of building that same wrapper against a
#   different debashl path. We create a temporary crate under .core-verify/
#   that points at sh2perl/backends/core, build it into an isolated target
#   dir (.core-verify-target/), print the binary path, and delete the
#   temporary crate on exit. The MAIN compiler target and binary are never
#   touched — the same isolation pattern main_loop_shir.pl uses.
#
# Usage:
#   bin=$(harness/core_verify.sh)          # build (or reuse) and print the path
#   harness/core_verify.sh --rebuild      # force a rebuild first
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SUB="$ROOT/sh2perl"                       # the sh2perl repo (worktree parent)
CORE="$SUB/backends/core"                 # the CORE worktree
# TEMPORARY wrapper crate, PER-PROCESS. It used to be a single fixed path
# ($ROOT/.core-verify), which made two concurrent runs destroy each other:
# each writes the crate, then `trap cleanup EXIT` does `rm -rf "$CRATE"`, so
# whichever finished first deleted the directory the other was still building
# in. The loser failed instantly with an empty stdout, which the core worker
# reported as "isolated core build FAILED" with NO cargo output — reproduced
# deterministically by running two at once (A rc=0, B rc=1, every round).
# A per-pid crate makes the trap safe by construction: it can only ever remove
# its own directory. The target dir stays SHARED (that is the point — it dedupes
# the dep build), and cargo's own target lock serialises the compiles.
CRATE="$ROOT/.core-verify.$$"             # temporary wrapper crate (gitignored)
TARGET="$ROOT/.core-verify-target"        # isolated cargo target (gitignored)
BIN="$TARGET/debug/otranspilerl-cli"

[ -d "$CORE/src" ] || { echo "core_verify: no core worktree at $CORE" >&2; exit 2; }

rebuild=0
for a in "$@"; do
  case "$a" in
    --rebuild) rebuild=1 ;;
    *) echo "core_verify: unknown option $a" >&2; exit 2 ;;
  esac
done

# A cached binary is only trusted if it is NEWER than every source it links:
# the wrapper's own sources and the whole core worktree. Compare the newest
# mtime against the binary's.
if [ "$rebuild" -eq 0 ] && [ -x "$BIN" ]; then
  newest=$(find "$ROOT/otranspilerl/src" "$ROOT/otranspilerl/Cargo.toml" "$CORE/src" "$CORE/Cargo.toml" -type f -newer "$BIN" -print -quit 2>/dev/null || true)
  if [ -z "$newest" ]; then
    echo "$BIN"
    exit 0
  fi
fi

cleanup() { rm -rf "$CRATE"; }
trap cleanup EXIT

mkdir -p "$CRATE/src"
cat > "$CRATE/Cargo.toml" <<EOF
# TEMPORARY crate — generated by harness/core_verify.sh, deleted on exit.
# The workspace otranspilerl crate minus the debashl path pin: it links the
# CORE worktree instead of the main checkout, so the core gate measures the
# core's own compiler.
[package]
name = "otranspilerl-core-verify"
version = "0.0.0"
edition = "2021"
publish = false

[lib]
name = "otranspilerl"
path = "src/lib.rs"
crate-type = ["rlib"]

[[bin]]
name = "otranspilerl-cli"
path = "src/main.rs"

[dependencies]
debashl = { path = "$CORE" }
serde_json = "1"

[workspace]
EOF

# Reuse the workspace wrapper's real sources verbatim (a copy, so the temp
# crate can never write into the workspace). Only the debashl pin differs.
cp "$ROOT/otranspilerl/src/lib.rs"  "$CRATE/src/lib.rs"
cp "$ROOT/otranspilerl/src/main.rs" "$CRATE/src/main.rs"
if [ -f "$ROOT/otranspilerl/src/wasi.rs" ]; then
  cp "$ROOT/otranspilerl/src/wasi.rs" "$CRATE/src/wasi.rs"
fi

mkdir -p "$TARGET"
"$ROOT/harness/build-lock.sh" --role core --share-target "$TARGET" -- \
  cargo build --manifest-path "$CRATE/Cargo.toml" --bin otranspilerl-cli >>"$ROOT/loop-core-worker.log" 2>&1 || {
  echo "core_verify: isolated core build FAILED (see loop-core-worker.log)" >&2
  exit 1
}

[ -x "$BIN" ] || { echo "core_verify: build produced no binary at $BIN" >&2; exit 1; }
echo "$BIN"
